"""ra_report.py - write out/REPORT.md from out/results.json. Every number in the report is read from the results.

    python ra_report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"


def e(x, d=1):
    """1.2e+14 -> 1.2e14"""
    m, p = f"{x:.{d}e}".split("e")
    return f"{m}e{int(p)}"


def main():
    r = json.load(open(OUT / "results.json"))
    R, S, C = r["results"], r["sources"], r["consensus"]
    models = list(R["Qa"])
    full = r["island_consensus"]["Qa"]["models"]
    W84 = r["window_paper_selection_Z_ge_84"]
    L = []
    a = L.append

    pc5 = {m: W84[m]["window"][1]["Pc95_baryon"] for m in full}
    pcall = [w["Pc95_baryon"] for m in full for w in W84[m]["window"]]
    zs = [w["z"] for m in full for w in W84[m]["window"]]
    ref = pc5["WS-Ma2019"]
    a("# Residual anomaly search, first pass: nuclear binding energies and alpha-decay energies")
    a("")
    a(f"Generated by `residual_analyzer.py` (seed {r['seed']}, Z >= {r['zmin']}, {r['nsim']} look-elsewhere "
      "simulations per search). Every number below is read from `out/results.json`.")
    a("")
    a("## Verdict")
    a("")
    a(f"- **No anomaly.** Of {C['Qa']['features_compared']:,} candidate features in the alpha-decay energies and "
      f"{C['B']['features_compared']:,} in the binding energies, none reaches 3 sigma in every mass model. "
      f"Only {C['Qa']['n_consensus_ge_2']} and {C['B']['n_consensus_ge_2']} reach even 2 sigma in every model.")
    a(f"- **The paper's window shows no signal in any model.** For a charge switched on at (Z, N) = (114, 184), "
      f"the fitted amplitude sits between {min(zs):+.1f} and {max(zs):+.1f} sigma across the four models that "
      "reach Z = 118 and the four widths the paper quotes.")
    a(f"- **The paper's ceiling is robust to the choice of mass model.** At width 5 the 95% ceiling on the central "
      f"strength is {e(ref)} with the paper's model and {e(min(pc5.values()))} to {e(max(pc5.values()))} across "
      f"the four models ({(min(pc5.values()) / ref - 1) * 100:+.0f}% to {(max(pc5.values()) / ref - 1) * 100:+.0f}%). "
      f"Over widths 4.5 to 10 it spans {e(min(pcall))} to {e(max(pcall))}.")
    g = {n["nuclide"]: n for n in r["precision_gaps"]["nuclides"]}
    a(f"- **Nuclear energies cannot see the charge in plutonium or curium.** The largest shift the paper's window "
      f"still allows in the mass of Pu-244 is {e(g['Pu-244']['B']['max_allowed_shift_keV'])} keV, against a "
      f"measurement good to {g['Pu-244']['B']['sigma_exp_keV']:.1f} keV. Only a force measurement reaches it.")
    at = {n["nuclide"]: n for n in r["atomic"]["nuclides"]}
    a(f"- **Atomic spectroscopy cannot see it either.** The force between an electron and a Pu-244 nucleus would "
      f"shift optical frequencies by at most {e(at['Pu-244']['fractional_frequency_shift'])} of themselves, "
      f"{e(at['Pu-244']['short_of_best_clocks_by'], 0)} times below the best optical clocks.")
    a("")
    a("## 1. Data and where it stops")
    a("")
    A = S["AME2020"]
    a(f"Experiment: AME2020 ({A['ref']}). {A['nuclides']} nuclides listed, {A['measured_masses']} with measured "
      f"masses and {A['estimated_masses']} estimated from systematics (marked # in the evaluation). Estimated "
      "values are never used. The mass table and the reaction-energy table agree on every alpha-decay energy to "
      f"{A['qalpha_cross_check_max_keV']:.3f} keV.")
    a("")
    a("| Model | Type | Reaches Z | Error vs AME2020, all nuclei (keV) | Z >= 82 (keV) | Source |")
    a("|---|---|---|---|---|---|")
    for m in models:
        s = S[m]
        a(f"| {m} | {s['family']} | {s['Zmax']} | {s['rms_vs_AME2020_keV']['all_measured']:.0f} | "
          f"{s['rms_vs_AME2020_keV']['Z_ge_82']:.0f} | {s['ref']} |")
    a("")
    a("No rows were rejected in any table. HFB-24 stops at Z = 110, so it cannot test anything above darmstadtium.")
    a("")
    a("Where the measurements stop (even-Z elements):")
    a("")
    a("| Z | Element | Measured masses, N range | Masses only estimated | Measured alpha energies, N range |")
    a("|---|---|---|---|---|")
    for Z in range(92, 119, 2):
        c = r["coverage"][str(Z)]
        mm = f"{c['N_mass_measured'][0]}-{c['N_mass_measured'][1]} ({c['n_mass_measured']})" if c["N_mass_measured"] else "DATA_GAP"
        qa = f"{c['N_qa_measured'][0]}-{c['N_qa_measured'][1]} ({c['n_qa_measured']})" if c["N_qa_measured"] else "DATA_GAP"
        a(f"| {Z} | {c['el']} | {mm} | {c['n_mass_estimated']} | {qa} |")
    a("")
    big = [f"{r['coverage'][z]['el']} N={n}" for z in r["coverage"] for n in r["coverage"][z]["qa_sigma_gt_100keV"]]
    a("Measured masses end at darmstadtium (Z = 110). Above it only alpha-decay energies are measured, and no "
      "measured nuclide lies within 7 neutrons of N = 184. Measured alpha energies with an uncertainty above "
      f"100 keV: {len(big)} ({', '.join(big[:12])}{', ...' if len(big) > 12 else ''}).")
    a("")
    a("## 2. Generic search, one model at a time")
    a("")
    a("Residual = measured minus model. The noise model is the model's own correlated error (fitted to the "
      "residuals) plus the experimental error. The search bank holds single nuclides, bumps of three widths, and "
      "steps and changes of slope along N and Z. `p` is corrected for the number of places searched.")
    a("")
    for obs, name in (("Qa", "Alpha-decay energies"), ("B", "Binding energies")):
        a(f"**{name}**")
        a("")
        a("| Model | n | rms (keV) | Strongest feature | z | p | Features at 3 sigma (expected by chance) |")
        a("|---|---|---|---|---|---|---|")
        for m in models:
            x = R[obs][m]; gg = x["generic"]["all"]
            a(f"| {m} | {x['n']} | {x['rms_keV']:.0f} | {gg['what']} | {gg['z']:+.1f} | "
              f"{'< 0.001' if gg['p_global'] < 0.001 else format(gg['p_global'], '.3f')} | "
              f"{x['n_local_3sigma']} ({x['n_local_3sigma_expected_null']:.0f}) |")
        a("")
    a("Every model shows features far beyond chance. They are the models' own errors, not physics: the strongest "
      "sit at Z = 83 to 85 and N = 125 to 131, around the doubly magic nucleus Pb-208, where each model misses the "
      "shell closure in its own way, and no two models agree on them (next section).")
    a("")
    a("## 3. What the models agree on")
    a("")
    a("A real effect is in the data, so every model must show it with the same sign. Each feature is scored by "
      "the smallest |z| among the models, counted only if all agree in sign.")
    a("")
    for obs, name in (("Qa", "Alpha-decay energies"), ("B", "Binding energies")):
        c = C[obs]
        a(f"**{name}:** {c['features_compared']:,} features compared, {c['n_consensus_ge_3']} at 3 sigma in every "
          f"model, {c['n_consensus_ge_2']} at 2 sigma.")
        a("")
        a("| Feature | Smallest abs(z) | " + " | ".join(models) + " |")
        a("|---|---|" + "---|" * len(models))
        for t in c["top"][:6]:
            a(f"| {t['what']} | {t['consensus']:.1f} | " + " | ".join(
                f"{t['z'][m]:+.1f}" if m in t["z"] else "no data" for m in models) + " |")
        a("")
    a("The strongest shared feature in the alpha energies is Ds-273 (Z = 110, N = 163) with its neighbours: high "
      "at N = 163 to 164, low at Hs-270 (N = 162). That is the pattern expected if every model slightly "
      "underestimates the deformed shell gap at N = 162, a known feature of this region. In the binding energies "
      "the shared features are neutron-deficient nuclei near lead (N = 103 to 118), a region known for shape "
      "coexistence and close-lying isomers. Neither is near the island, and neither reaches 3 sigma.")
    a("")
    cc = r["residual_correlation_between_models"]
    a(f"The models' residuals are only weakly correlated with each other ({min(cc['Qa'].values()):+.2f} to "
      f"{max(cc['Qa'].values()):+.2f} for alpha energies, {min(cc['B'].values()):+.2f} to "
      f"{max(cc['B'].values()):+.2f} for binding energies), which is what makes the cross-model test informative.")
    a("")
    a("## 4. The paper's window")
    a("")
    a("The self-energy of a scalar charge that switches on as a Gaussian around (114, 184) lowers the masses of "
      "nuclei near the island and shifts their alpha-decay energies. The table repeats the paper's Sec. II D fit "
      "(its selection, Z >= 84) for every model. P_c is the 95% ceiling on the central strength in units of "
      "gravity, baryon-number reading.")
    a("")
    a("| Model | n | z at width 5 | P_c ceiling, width 4.5 | 5 | 7 | 10 |")
    a("|---|---|---|---|---|---|---|")
    for m in models:
        x = W84[m]
        a(f"| {m}{'' if x['Zmax'] >= 118 else ' (stops at Z = 110)'} | {x['n']} | {x['window'][1]['z']:+.2f} | "
          + " | ".join(e(w["Pc95_baryon"]) for w in x["window"]) + " |")
    a("")
    v = r["validation"]
    a(f"Check: with the paper's model this code reproduces the paper's limits to a ratio of "
      f"{max(abs(x - 1) for x in v['qc95_ratio_to_paper'].values()):.0e} (n = {v['n']}).")
    a("")
    ic = r["island_consensus"]["Qa"]
    a(f"Scan of where an island could sit instead ({ic['centres']:,} centre and width combinations, Z 100 to 126, "
      f"N 150 to 196): the best single-model excesses are "
      + ", ".join(f"{m} {R['Qa'][m]['island_scan']['max_z']:.1f} sigma (p = {R['Qa'][m]['island_scan']['p_global']:.2f})"
                  for m in full)
      + f". They sit at different places. Requiring all four models, the best location reaches only "
        f"{ic['top'][0]['min_z']:.1f} sigma (Z = {ic['top'][0]['Zc']}, N = {ic['top'][0]['Nc']}), and none reaches 2.")
    a("")
    a("The binding-energy channel adds nothing here: measured masses stop at Z = 110, too far from the island "
      f"(its ceilings are {e(min(w['Pc95_baryon'] for m in models for w in R['B'][m]['window']))} or weaker).")
    a("")
    a("## 5. Precision gaps")
    a("")
    pg = r["precision_gaps"]
    a("For each nuclide: the largest shift the paper's window still allows (ceiling from section 4, taking the "
      f"weakest of {', '.join(pg['models_used'])}, and the uranium bound), against what is measured. "
      "DATA_GAP = no measurement exists.")
    a("")
    a("| Nuclide | Mass: measured to (keV) | Largest allowed shift (keV) | Alpha energy: measured to (keV) | Largest allowed shift (keV) | Shift / model error |")
    a("|---|---|---|---|---|---|")
    for n in pg["nuclides"]:
        b, q = n["B"], n["Qa"]
        sb = f"{b['sigma_exp_keV']:.2g}" if b["status"] == "measured" else "DATA_GAP"
        sq = f"{q['sigma_exp_keV']:.2g}" if q["status"] == "measured" else "DATA_GAP"
        a(f"| {n['nuclide']} | {sb} | {e(b['max_allowed_shift_keV'])} | {sq} | {e(q['max_allowed_shift_keV'])} | "
          f"{e(q['shift_over_model_error'])} |")
    a("")
    a(f"The mass models are good to about {pg['model_error_keV']:.0f} keV near the island, and that, not the "
      "measurements, sets the ceiling. For the superheavy nuclides the allowed shift is comparable to the model "
      "error, which is why they constrain the charge at all. For plutonium and curium it is smaller by more than "
      "twenty orders of magnitude: the self-energy goes as the square of the nuclide's own charge, which is tiny "
      "that far from the island. A torsion balance measures the product of that charge with ordinary matter's, "
      "which is why it is the only probe that reaches these nuclides.")
    a("")
    a("## 6. Atomic sector: DATA_GAP, and not worth filling for this force")
    a("")
    aa = r["atomic"]
    a("No isotope-shift or transition-frequency data were ingested. Before building a King-plot analyser, this "
      "pass computed how large the effect could be. Between an electron and a nucleus the paper's force is a "
      f"1/r term {e(aa['prefactor_gravity_over_coulomb'], 2)} x (A/Z) x P_X times the Coulomb attraction. The "
      "electron carries a charge only in the mass-like reading, so these are upper limits.")
    a("")
    a("| Nuclide | Largest allowed P_X | Fractional frequency shift | Times below the best optical clocks |")
    a("|---|---|---|---|")
    for n in aa["nuclides"]:
        a(f"| {n['nuclide']} | {e(n['P_X'])} | {e(n['fractional_frequency_shift'])} | {e(n['short_of_best_clocks_by'], 0)} |")
    a("")
    a(f"The best optical frequency comparisons reach about {e(aa['best_clock_fraction'], 0)}, on stable or "
      "long-lived atoms. Superheavy atoms are made one at a time and live for seconds or less. A King-plot "
      "analysis would test a different kind of new force (one coupled to electrons far more strongly than "
      "gravity); it cannot test this one.")
    a("")
    a("## 7. Limits of this pass")
    a("")
    a("- The single-model p-values assume the fitted noise model is right. Section 2 shows it is not near shell "
      "closures, so they overstate significance. The cross-model test of section 3 does not rely on them.")
    a("- The cross-model score is a screen, not a p-value: models share physics, so their errors are not fully "
      "independent.")
    a("- The noise model is fitted to the same residuals that are searched, which makes the search conservative "
      "for features about as wide as the fitted correlation length (1.3 to 3.9 nucleons).")
    a("- FRDM2012 comes from the text of the arXiv PDF (two decimals in MeV). Each row was checked against its "
      "own binding-energy column and all 9,318 published rows passed.")
    a("- Charge radii and isotope shifts are not ingested. Section 6 explains why that is not a priority.")
    a("")
    a("Figures: `fig1_qalpha_residual_maps.png`, `fig2_ceiling_by_model.png`, `fig3_consensus.png`.")
    (OUT / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT / "REPORT.md", f"({len(L)} lines)")


if __name__ == "__main__":
    main()
